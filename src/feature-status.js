/** 给后台页签用：按组整理 */
export function featureGroups() {
  const groups = [];
  for (const f of FEATURE_STATUS) {
    let g = groups.find((x) => x.name === f.group);
    if (!g) { g = { name: f.group, items: [] }; groups.push(g); }
    g.items.push(f);
  }
  return groups;
}

